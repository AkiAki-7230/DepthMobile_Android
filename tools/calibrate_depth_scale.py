"""Fit a deployment-safe residual scale for the existing YOLO26-depth NCNN output.

Input CSV columns:
    device_id,sample_id,predicted_m,ground_truth_m

The fit mirrors Ultralytics' scale-only log-depth calibration, but operates on distances
already produced by the Android NCNN model. Device-level cross-validation prevents frames
from one phone leaking into that phone's score.
"""

from __future__ import annotations

import argparse
import csv
import math
from dataclasses import dataclass
from pathlib import Path
from statistics import fmean


MIN_ALLOWED_SCALE = 0.25
MAX_ALLOWED_SCALE = 4.0


@dataclass(frozen=True)
class Sample:
    device_id: str
    sample_id: str
    predicted_m: float
    ground_truth_m: float


@dataclass(frozen=True)
class Metrics:
    delta1: float
    abs_rel: float
    rmse: float


def load_samples(path: Path, minimum_m: float, maximum_m: float) -> list[Sample]:
    samples: list[Sample] = []
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        required = {"device_id", "sample_id", "predicted_m", "ground_truth_m"}
        missing = required.difference(reader.fieldnames or ())
        if missing:
            raise ValueError(f"Missing CSV columns: {', '.join(sorted(missing))}")

        for line_number, row in enumerate(reader, start=2):
            device_id = (row["device_id"] or "").strip()
            sample_id = (row["sample_id"] or "").strip()
            try:
                predicted_m = float(row["predicted_m"])
                ground_truth_m = float(row["ground_truth_m"])
            except (TypeError, ValueError) as error:
                raise ValueError(f"Invalid distance on CSV line {line_number}") from error

            if not device_id or not sample_id:
                raise ValueError(f"Blank device_id/sample_id on CSV line {line_number}")
            if not math.isfinite(predicted_m) or predicted_m <= 0:
                continue
            if not math.isfinite(ground_truth_m) or not minimum_m <= ground_truth_m <= maximum_m:
                continue
            samples.append(Sample(device_id, sample_id, predicted_m, ground_truth_m))

    if not samples:
        raise ValueError("No valid calibration samples remain after filtering")
    return samples


def group_by_device(samples: list[Sample]) -> dict[str, list[Sample]]:
    grouped: dict[str, list[Sample]] = {}
    for sample in samples:
        grouped.setdefault(sample.device_id, []).append(sample)
    return grouped


def fit_device_balanced_scale(samples: list[Sample]) -> float:
    grouped = group_by_device(samples)
    device_log_offsets = [
        fmean(math.log(sample.ground_truth_m) - math.log(sample.predicted_m) for sample in device_samples)
        for device_samples in grouped.values()
    ]
    return math.exp(fmean(device_log_offsets))


def calculate_metrics(samples: list[Sample], scale: float) -> Metrics:
    ratios: list[float] = []
    relative_errors: list[float] = []
    squared_errors: list[float] = []
    for sample in samples:
        calibrated = sample.predicted_m * scale
        ratios.append(max(calibrated / sample.ground_truth_m, sample.ground_truth_m / calibrated))
        relative_errors.append(abs(calibrated - sample.ground_truth_m) / sample.ground_truth_m)
        squared_errors.append((calibrated - sample.ground_truth_m) ** 2)
    return Metrics(
        delta1=fmean(ratio < 1.25 for ratio in ratios),
        abs_rel=fmean(relative_errors),
        rmse=math.sqrt(fmean(squared_errors))
    )


def leave_one_device_out(samples: list[Sample]) -> tuple[Metrics, Metrics]:
    grouped = group_by_device(samples)
    if len(grouped) < 2:
        raise ValueError("At least two device_id values are required for held-out validation")

    raw_device_metrics: list[Metrics] = []
    calibrated_device_metrics: list[Metrics] = []
    for held_out_device, held_out_samples in grouped.items():
        fit_samples = [sample for sample in samples if sample.device_id != held_out_device]
        scale = fit_device_balanced_scale(fit_samples)
        raw_device_metrics.append(calculate_metrics(held_out_samples, 1.0))
        calibrated_device_metrics.append(calculate_metrics(held_out_samples, scale))

    def macro_average(values: list[Metrics]) -> Metrics:
        return Metrics(
            delta1=fmean(value.delta1 for value in values),
            abs_rel=fmean(value.abs_rel for value in values),
            rmse=fmean(value.rmse for value in values)
        )

    return macro_average(raw_device_metrics), macro_average(calibrated_device_metrics)


def write_properties(
    path: Path,
    scale: float,
    source: str,
    sample_count: int,
    held_out_devices: int
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Generated by tools/calibrate_depth_scale.py\n"
        f"correction_scale={scale:.8f}\n"
        f"source={source}\n"
        f"sample_count={sample_count}\n"
        f"held_out_devices={held_out_devices}\n",
        encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--min-distance", type=float, default=0.20)
    parser.add_argument("--max-distance", type=float, default=20.0)
    parser.add_argument("--delta1-margin", type=float, default=0.005)
    args = parser.parse_args()

    if args.min_distance <= 0 or args.max_distance <= args.min_distance:
        raise ValueError("Invalid calibration distance range")

    samples = load_samples(args.csv, args.min_distance, args.max_distance)
    grouped = group_by_device(samples)
    raw_cv, calibrated_cv = leave_one_device_out(samples)
    candidate_scale = fit_device_balanced_scale(samples)

    improves_delta1 = calibrated_cv.delta1 >= raw_cv.delta1 + args.delta1_margin
    does_not_worsen_abs_rel = calibrated_cv.abs_rel <= raw_cv.abs_rel
    selected = improves_delta1 and does_not_worsen_abs_rel
    selected_scale = candidate_scale if selected else 1.0
    if not MIN_ALLOWED_SCALE <= selected_scale <= MAX_ALLOWED_SCALE:
        raise ValueError(
            f"Selected scale {selected_scale:.6f} is outside the Android safety range "
            f"{MIN_ALLOWED_SCALE}..{MAX_ALLOWED_SCALE}"
        )

    source = "multi_device_scale_only_cv" if selected else "identity_cv_rejected_scale"
    write_properties(args.output, selected_scale, source, len(samples), len(grouped))

    print(f"samples={len(samples)} devices={len(grouped)}")
    print(
        "raw_cv "
        f"delta1={raw_cv.delta1:.4f} abs_rel={raw_cv.abs_rel:.4f} rmse={raw_cv.rmse:.4f}"
    )
    print(
        "calibrated_cv "
        f"delta1={calibrated_cv.delta1:.4f} abs_rel={calibrated_cv.abs_rel:.4f} "
        f"rmse={calibrated_cv.rmse:.4f}"
    )
    print(
        f"selected={source} correction_scale={selected_scale:.8f} output={args.output}"
    )


if __name__ == "__main__":
    main()
